class CodeGenerator {
  static generateScikitLearnCode(pipelineName, nodes, datasetMeta) {
    let imports = [
      'import pandas as pd',
      'from sklearn.pipeline import Pipeline'
    ];
    let pipelineSteps = [];

    nodes.forEach(node => {
      switch (node.name) {
        case 'SimpleImputer':
          if (!imports.includes('from sklearn.impute import SimpleImputer')) {
            imports.push('from sklearn.impute import SimpleImputer');
          }
          pipelineSteps.push(`    ('imputer', SimpleImputer(strategy='mean'))`);
          break;
        case 'StandardScaler':
          if (!imports.includes('from sklearn.preprocessing import StandardScaler')) {
            imports.push('from sklearn.preprocessing import StandardScaler');
          }
          pipelineSteps.push(`    ('scaler', StandardScaler())`);
          break;
        case 'OneHotEncoder':
          if (!imports.includes('from sklearn.preprocessing import OneHotEncoder')) {
            imports.push('from sklearn.preprocessing import OneHotEncoder');
          }
          pipelineSteps.push(`    ('encoder', OneHotEncoder(handle_unknown='ignore'))`);
          break;
        case 'SMOTE':
          if (!imports.includes('from imblearn.over_sampling import SMOTE')) {
            imports.push('from imblearn.pipeline import Pipeline as ImbPipeline');
            imports.push('from imblearn.over_sampling import SMOTE');
            // We need to use imblearn's pipeline for SMOTE
            imports = imports.filter(imp => imp !== 'from sklearn.pipeline import Pipeline');
          }
          pipelineSteps.push(`    ('smote', SMOTE())`);
          break;
        case 'RandomForestClassifier':
          if (!imports.includes('from sklearn.ensemble import RandomForestClassifier')) {
            imports.push('from sklearn.ensemble import RandomForestClassifier');
          }
          pipelineSteps.push(`    ('model', RandomForestClassifier(n_estimators=100, random_state=42))`);
          break;
        case 'RandomForestRegressor':
          if (!imports.includes('from sklearn.ensemble import RandomForestRegressor')) {
            imports.push('from sklearn.ensemble import RandomForestRegressor');
          }
          pipelineSteps.push(`    ('model', RandomForestRegressor(n_estimators=100, random_state=42))`);
          break;
        case 'LogisticRegression':
          if (!imports.includes('from sklearn.linear_model import LogisticRegression')) {
            imports.push('from sklearn.linear_model import LogisticRegression');
          }
          pipelineSteps.push(`    ('model', LogisticRegression(max_iter=1000))`);
          break;
        case 'LinearRegression':
          if (!imports.includes('from sklearn.linear_model import LinearRegression')) {
            imports.push('from sklearn.linear_model import LinearRegression');
          }
          pipelineSteps.push(`    ('model', LinearRegression())`);
          break;
        case 'XGBClassifier':
          if (!imports.includes('from xgboost import XGBClassifier')) {
            imports.push('from xgboost import XGBClassifier');
          }
          pipelineSteps.push(`    ('model', XGBClassifier(n_estimators=100, random_state=42))`);
          break;
        case 'XGBRegressor':
          if (!imports.includes('from xgboost import XGBRegressor')) {
            imports.push('from xgboost import XGBRegressor');
          }
          pipelineSteps.push(`    ('model', XGBRegressor(n_estimators=100, random_state=42))`);
          break;
      }
    });

    const pipelineClass = imports.some(i => i.includes('ImbPipeline')) ? 'ImbPipeline' : 'Pipeline';
    const hasTarget = datasetMeta.target_type !== 'unknown';

    return `
# ${pipelineName} - Auto-Generated by KLCAP-2026 Meta-Learned Platform
# Target Type: ${datasetMeta.target_type}
# Num Rows: ${datasetMeta.num_rows}

${imports.join('\n')}

def get_pipeline():
    """
    Returns the scikit-learn compatible pipeline.
    """
    pipeline = ${pipelineClass}([
${pipelineSteps.join(',\n')}
    ])
    return pipeline

if __name__ == '__main__':
    print("Initializing pipeline...")
    pipe = get_pipeline()
    print(pipe)
    
    # Example Usage:
    # df = pd.read_csv('your_dataset.csv')
    ${hasTarget ? `# X = df.drop(columns=['target_column'])
    # y = df['target_column']
    # pipe.fit(X, y)` : `# pipe.fit(df)`}
    # print("Pipeline fitted successfully!")
`;
  }
}

module.exports = CodeGenerator;
