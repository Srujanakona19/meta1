import { useState, useEffect } from 'react';
import { motion } from 'framer-motion';
import { Database, TrendingUp, Calendar, ArrowUpDown, FileDown } from 'lucide-react';
import { getExperiments } from '../services/api';
import { toast } from 'sonner';
import jsPDF from 'jspdf';
import {
  useReactTable,
  getCoreRowModel,
  getSortedRowModel,
  flexRender,
} from '@tanstack/react-table';

export function Experiments() {
  const [data, setData] = useState([]);
  const [sorting, setSorting] = useState([]);
  const [loading, setLoading] = useState(true);

  const downloadReport = (exp) => {
    try {
      const doc = new jsPDF();
      
      // Header styling
      doc.setFillColor(10, 15, 29);
      doc.rect(0, 0, 210, 45, 'F');
      
      doc.setTextColor(0, 240, 255);
      doc.setFontSize(20);
      doc.setFont('helvetica', 'bold');
      doc.text("KLCAP-2026", 14, 20);
      
      doc.setTextColor(255, 255, 255);
      doc.setFontSize(11);
      doc.setFont('helvetica', 'normal');
      doc.text("Automated Meta-Learned ML Pipeline Report", 14, 28);
      doc.text(`Generated: ${new Date().toLocaleString()}`, 14, 36);

      // Section: Overview
      doc.setTextColor(20, 20, 20);
      doc.setFontSize(14);
      doc.setFont('helvetica', 'bold');
      doc.text("Experiment Details", 14, 60);

      doc.setFontSize(10);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(60, 60, 60);
      
      const rows = [
        ["Experiment ID", exp.id],
        ["Target Dataset", exp.dataset || "N/A"],
        ["Run Date", exp.date],
        ["Recommended Pipeline", exp.pipeline],
        ["Recommendation Confidence", `${exp.conf}%`],
        ["Estimated Test Performance", `${exp.perf}%`],
        ["Dataset Shift Risk", exp.shift],
      ];

      let yPos = 72;
      rows.forEach(([label, value]) => {
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(40, 40, 40);
        doc.text(`${label}:`, 14, yPos);
        doc.setFont('helvetica', 'normal');
        doc.setTextColor(80, 80, 80);
        doc.text(String(value), 80, yPos);
        yPos += 10;
      });

      // Verification Box
      doc.setDrawColor(0, 200, 220);
      doc.setFillColor(245, 252, 255);
      doc.roundedRect(14, yPos + 10, 182, 35, 3, 3, 'FD');
      
      doc.setFontSize(11);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(0, 130, 160);
      doc.text("Meta-Learning Recommendation Verdict", 20, yPos + 22);
      
      doc.setFontSize(9);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(60, 70, 80);
      doc.text(
        `Pipeline '${exp.pipeline}' was selected based on meta-feature similarity to historical datasets.`,
        20,
        yPos + 32
      );

      // Footer
      doc.setFontSize(8);
      doc.setTextColor(140, 140, 140);
      doc.text("Generated by KLCAP-2026 Meta-Learning System | Confidential & Automated", 14, 285);

      doc.save(`${exp.id}_pipeline_report.pdf`);
      toast.success(`Report for ${exp.id} downloaded!`);
    } catch (err) {
      console.error(err);
      toast.error("Failed to generate PDF report.");
    }
  };

  useEffect(() => {
    getExperiments().then(res => {
      // Map API response to table format
      const mapped = res.map(row => ({
        id: `EXP-${row.id}`,
        dataset: row.dataset_name,
        date: new Date(row.created_at).toISOString().split('T')[0],
        pipeline: row.recommended_pipeline,
        conf: (row.confidence * 100).toFixed(1),
        shift: row.missing_ratio > 0.5 ? 'HIGH' : 'LOW',
        perf: (row.confidence * 95).toFixed(1)
      }));
      setData(mapped);
    }).catch(err => {
      toast.error(err.message || 'Failed to load experiments');
    }).finally(() => {
      setLoading(false);
    });
  }, []);

  const columns = [
    {
      accessorKey: 'id',
      header: 'Experiment ID',
      cell: info => <span className="font-mono text-[var(--color-brand-blue)]">{info.getValue()}</span>,
    },
    {
      accessorKey: 'dataset',
      header: 'Dataset',
      cell: info => <div className="flex items-center gap-2"><Database className="w-4 h-4 text-white/50" /> {info.getValue()}</div>,
    },
    {
      accessorKey: 'date',
      header: 'Date',
      cell: info => <div className="flex items-center gap-2"><Calendar className="w-4 h-4 text-white/50" /> {info.getValue()}</div>,
    },
    {
      accessorKey: 'pipeline',
      header: 'Recommended Pipeline',
      cell: info => <span className="font-bold">{info.getValue()}</span>,
    },
    {
      accessorKey: 'conf',
      header: 'Confidence',
      cell: info => <span>{info.getValue()}%</span>,
    },
    {
      accessorKey: 'shift',
      header: 'Shift Risk',
      cell: info => {
        const val = info.getValue();
        return <span className={val === 'LOW' ? 'text-green-400' : val === 'MODERATE' ? 'text-yellow-400' : 'text-red-400'}>{val}</span>;
      },
    },
    {
      accessorKey: 'perf',
      header: 'Est. Performance',
      cell: info => <div className="flex items-center gap-2"><TrendingUp className="w-4 h-4 text-white/50" /> {info.getValue()}%</div>,
    },
    {
      id: 'actions',
      header: 'Report',
      cell: ({ row }) => (
        <button
          onClick={() => downloadReport(row.original)}
          className="flex items-center gap-1.5 px-3 py-1.5 bg-white/5 hover:bg-[var(--color-brand-blue)]/20 text-xs font-semibold rounded-lg text-white hover:text-[var(--color-brand-blue)] transition-all border border-white/10"
        >
          <FileDown className="w-3.5 h-3.5" /> PDF
        </button>
      ),
    },
  ];

  const table = useReactTable({
    data,
    columns,
    state: {
      sorting,
    },
    onSortingChange: setSorting,
    getCoreRowModel: getCoreRowModel(),
    getSortedRowModel: getSortedRowModel(),
  });

  return (
    <div className="py-12 px-8 md:px-16 min-h-screen">
      <motion.div initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} className="max-w-7xl mx-auto">
        <h1 className="text-4xl font-bold mb-4">Experiment History</h1>
        <p className="text-white/60 mb-12">Track previous dataset analyses and pipeline recommendations with sortable data grids.</p>
        
        <div className="glass-panel rounded-2xl overflow-hidden border border-white/10">
          <div className="overflow-x-auto">
            <table className="w-full text-left">
              <thead className="bg-black/40 border-b border-white/10 text-xs uppercase tracking-widest text-white/50">
                {table.getHeaderGroups().map(headerGroup => (
                  <tr key={headerGroup.id}>
                    {headerGroup.headers.map(header => (
                      <th 
                        key={header.id} 
                        className="px-6 py-4 cursor-pointer hover:text-white transition-colors select-none"
                        onClick={header.column.getToggleSortingHandler()}
                      >
                        <div className="flex items-center gap-2">
                          {flexRender(header.column.columnDef.header, header.getContext())}
                          {{
                            asc: <ArrowUpDown className="w-3 h-3 text-[var(--color-brand-blue)]" />,
                            desc: <ArrowUpDown className="w-3 h-3 text-[var(--color-brand-purple)]" />,
                          }[header.column.getIsSorted()] ?? <ArrowUpDown className="w-3 h-3 opacity-20" />}
                        </div>
                      </th>
                    ))}
                  </tr>
                ))}
              </thead>
              <tbody className="divide-y divide-white/5">
                {loading ? (
                  <tr><td colSpan={8} className="px-6 py-8 text-center text-white/50">Loading experiments...</td></tr>
                ) : data.length === 0 ? (
                  <tr><td colSpan={8} className="px-6 py-8 text-center text-white/50">No experiments run yet. Go analyze a dataset!</td></tr>
                ) : (
                  table.getRowModel().rows.map(row => (
                    <tr key={row.id} className="hover:bg-white/5 transition-colors">
                      {row.getVisibleCells().map(cell => (
                        <td key={cell.id} className="px-6 py-4 text-sm">
                          {flexRender(cell.column.columnDef.cell, cell.getContext())}
                        </td>
                      ))}
                    </tr>
                  ))
                )}
              </tbody>
            </table>
          </div>
        </div>
      </motion.div>
    </div>
  );
}
